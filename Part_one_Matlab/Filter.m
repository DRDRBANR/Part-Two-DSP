% Коэффициенты числителя (b) и знаменателя (a) передаточной функции
b = [0.0089, -0.0045, -0.0045, 0.0089];
a = [1, -2.5641, 2.2185, -0.6456];

% Количество точек для расчета (определяет разрешающую способность графиков)
N = 1024;

% Расчет комплексного частотного отклика
[h, w] = freqz(b, a, N);

% Вычисление АЧХ в логарифмическом масштабе (децибелы)
mag_dB = 20 * log10(abs(h));

% Вычисление ФЧХ в радианах с применением функции непрерывной развертки фазы
phase_rad = unwrap(angle(h));

% Расчет группового времени запаздывания (в дискретных отсчетах)
[gd, w_gd] = grpdelay(b, a, N);

% --- Добавленный блок: Расчет уровня подавления в полосе заграждения ---

% Определение индекса массива, соответствующего границе полосы заграждения (w = pi/4)
ws_index = find(w >= pi/4, 1);

% Поиск максимального коэффициента передачи в диапазоне заграждения
[max_stopband_dB, max_idx_relative] = max(mag_dB(ws_index:end));

% Вычисление абсолютного индекса найденного максимума для отображения на графике
max_idx_absolute = ws_index + max_idx_relative - 1;
w_max_stopband = w(max_idx_absolute);

% Вывод численного значения в командное окно MATLAB
fprintf('Гарантированный уровень подавления в полосе заграждения (w >= pi/4): %.2f дБ\n', max_stopband_dB);

% --- Конец добавленного блока ---

% Инициализация графического окна
figure('Name', 'Частотные характеристики цифрового фильтра', 'NumberTitle', 'off', 'Position', [100, 100, 800, 900]);

% Построение Амплитудно-частотной характеристики
subplot(3, 1, 1);
plot(w/pi, mag_dB, 'LineWidth', 1.5, 'Color', 'b');
hold on;
% Визуализация маркера максимума в полосе заграждения и опорной линии
plot(w_max_stopband/pi, max_stopband_dB, 'ro', 'MarkerSize', 6, 'MarkerFaceColor', 'r');
yline(max_stopband_dB, 'r--', sprintf(' Уровень подавления: %.2f дБ', max_stopband_dB), 'LabelHorizontalAlignment', 'left');
hold off;
grid on;
title('Амплитудно-частотная характеристика (АЧХ)');
xlabel('Нормированная круговая частота (\times\pi рад/период дискретизации)');
ylabel('Коэффициент передачи (дБ)');
xlim([0 1]);
ylim([-100 5]);

% Построение Фазочастотной характеристики
subplot(3, 1, 2);
plot(w/pi, phase_rad, 'LineWidth', 1.5, 'Color', 'r');
grid on;
title('Фазочастотная характеристика (ФЧХ)');
xlabel('Нормированная круговая частота (\times\pi рад/период дискретизации)');
ylabel('Фазовый сдвиг (рад)');
xlim([0 1]);

% Построение Группового времени запаздывания
subplot(3, 1, 3);
plot(w_gd/pi, gd, 'LineWidth', 1.5, 'Color', 'k');
grid on;
title('Групповое время запаздывания (ГВЗ)');
xlabel('Нормированная круговая частота (\times\pi рад/период дискретизации)');
ylabel('Задержка (период дискретизации)');
xlim([0 1]);